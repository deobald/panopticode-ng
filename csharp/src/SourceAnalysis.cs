using Microsoft.CodeAnalysis;
using Microsoft.CodeAnalysis.CSharp;
using Microsoft.CodeAnalysis.CSharp.Syntax;

namespace Panopticode.CSharp;

public static class SourceAnalysis
{
    private static readonly HashSet<string> Ignored = new(StringComparer.OrdinalIgnoreCase)
        { ".git", ".vs", ".idea", "bin", "obj", "packages", "node_modules", "vendor", "reports", "TestResults" };

    public static List<string> Discover(Options options)
    {
        var files = new List<string>();
        void Walk(string directory)
        {
            foreach (var path in Directory.EnumerateFileSystemEntries(directory).Order(StringComparer.Ordinal))
            {
                var info = File.GetAttributes(path);
                if ((info & FileAttributes.ReparsePoint) != 0 || IsWithin(path, options.Output)) continue;
                var relative = Path.GetRelativePath(options.Root, path).Replace('\\', '/');
                if (options.Excludes.Any(ex => relative == ex || relative.StartsWith(ex + "/", StringComparison.Ordinal) || (!ex.Contains('/') && Path.GetFileName(path) == ex))) continue;
                if ((info & FileAttributes.Directory) != 0)
                {
                    if (!Ignored.Contains(Path.GetFileName(path))) Walk(path);
                    continue;
                }
                if (!path.EndsWith(".cs", StringComparison.OrdinalIgnoreCase) || GeneratedName(path)) continue;
                using var reader = File.OpenText(path);
                var prefix = new char[1024];
                var count = reader.ReadBlock(prefix, 0, prefix.Length);
                if (new string(prefix, 0, count).Contains("<auto-generated", StringComparison.OrdinalIgnoreCase)) continue;
                files.Add(path);
            }
        }
        Walk(options.Root);
        return files;
    }

    public static bool IsWithin(string path, string root)
    {
        var relative = Path.GetRelativePath(root, path);
        return relative != ".." && !relative.StartsWith(".." + Path.DirectorySeparatorChar, StringComparison.Ordinal) && !Path.IsPathRooted(relative);
    }
    public static IEnumerable<string> DiscoverProjectFiles(string selected, string root)
    {
        if (selected.EndsWith(".csproj", StringComparison.OrdinalIgnoreCase)) return [selected];
        var directory = Path.GetDirectoryName(selected)!;
        IEnumerable<string> paths = selected.EndsWith(".slnx", StringComparison.OrdinalIgnoreCase)
            ? System.Xml.Linq.XDocument.Load(selected).Descendants("Project").Select(p => (string?)p.Attribute("Path") ?? "")
            : System.Text.RegularExpressions.Regex.Matches(File.ReadAllText(selected), "Project\\([^\\r\\n]+?=\\s*\"[^\"]*\",\\s*\"([^\"]+\\.csproj)\"", System.Text.RegularExpressions.RegexOptions.IgnoreCase, TimeSpan.FromSeconds(2)).Select(m => m.Groups[1].Value);
        return paths.Where(p => p.EndsWith(".csproj", StringComparison.OrdinalIgnoreCase)).Select(p => Path.GetFullPath(p.Replace('\\', '/'), directory)).Where(File.Exists).ToArray();
    }
    private static bool GeneratedName(string path) => new[] { ".g.cs", ".g.i.cs", ".designer.cs" }.Any(s => path.EndsWith(s, StringComparison.OrdinalIgnoreCase));

    public static SourceFile Measure(string path, Options options, Report report)
    {
        var tree = CSharpSyntaxTree.ParseText(File.ReadAllText(path), new CSharpParseOptions(LanguageVersion.Latest, preprocessorSymbols: options.Defines), path);
        var file = new SourceFile { Path = Path.GetRelativePath(options.Root, path).Replace('\\', '/'), PhysicalLines = tree.GetText().Lines.Count, Tree = tree };
        var errors = tree.GetDiagnostics().Where(d => d.Severity == DiagnosticSeverity.Error).ToArray();
        if (errors.Length > 0)
        {
            file.Parsed = false;
            foreach (var error in errors.Take(5)) report.Warnings.Add($"Syntax: {file.Path}:{error.Location.GetLineSpan().StartLinePosition.Line + 1}: {error.Id} {error.GetMessage()}");
            return file;
        }
        var root = tree.GetRoot();
        foreach (var node in root.DescendantNodes().Where(IsCallable)) file.Regions.Add(MeasureRegion(node, file.Path));
        var globals = root.ChildNodes().OfType<GlobalStatementSyntax>().ToArray();
        if (globals.Length > 0) file.Regions.Add(CreateRegion(root, "<top-level>", "top-level", globals.SelectMany(g => Owned(g)).ToArray(), file.Path));
        var initializers = root.DescendantNodes().OfType<EqualsValueClauseSyntax>().Where(n => n.Parent is PropertyDeclarationSyntax || n.Parent is VariableDeclaratorSyntax { Parent: VariableDeclarationSyntax { Parent: BaseFieldDeclarationSyntax } }).ToArray();
        if (initializers.Length > 0)
        {
            var region = CreateRegion(root, "<field/property initializers>", "initializers", initializers.SelectMany(n => Owned(n)).ToArray(), file.Path);
            file.Regions.Add(region with { Id = file.Path + ":initializers", Statements = initializers.Length, Line = Line(initializers[0]), EndLine = initializers[^1].GetLocation().GetLineSpan().EndLinePosition.Line + 1 });
        }
        foreach (var type in root.DescendantNodes().OfType<TypeDeclarationSyntax>())
            file.Types.Add(new(type.Identifier.Text, type.Kind().ToString(), Line(type), type.Members.OfType<BaseMethodDeclarationSyntax>().Count(), type.Members.OfType<BasePropertyDeclarationSyntax>().Count(), type.BaseList?.Types.Select(t => t.Type.ToString()).ToArray() ?? []));
        return file;
    }

    private static bool IsCallable(SyntaxNode node) => node is BaseMethodDeclarationSyntax { Body: not null } or BaseMethodDeclarationSyntax { ExpressionBody: not null }
        or LocalFunctionStatementSyntax or AnonymousFunctionExpressionSyntax or AccessorDeclarationSyntax { Body: not null } or AccessorDeclarationSyntax { ExpressionBody: not null }
        or PropertyDeclarationSyntax { ExpressionBody: not null } or IndexerDeclarationSyntax { ExpressionBody: not null };
    private static IEnumerable<SyntaxNode> Owned(SyntaxNode root) => root.DescendantNodesAndSelf(n => n == root || !IsCallable(n)).Where(n => n == root || !IsCallable(n));

    private static Region MeasureRegion(SyntaxNode node, string path)
    {
        var name = node switch
        {
            MethodDeclarationSyntax m => m.Identifier.Text,
            ConstructorDeclarationSyntax c => c.Identifier.Text,
            DestructorDeclarationSyntax d => "~" + d.Identifier.Text,
            LocalFunctionStatementSyntax l => l.Identifier.Text,
            AccessorDeclarationSyntax a => a.Parent?.Parent is BasePropertyDeclarationSyntax p ? p.ToString().Split('\n')[0].Split('{')[0].Trim() + "." + a.Keyword.Text : a.Keyword.Text,
            PropertyDeclarationSyntax p => p.Identifier.Text,
            IndexerDeclarationSyntax => "this[]",
            _ => node.Kind().ToString()
        };
        var containing = node.Ancestors().OfType<TypeDeclarationSyntax>().Select(t => t.Identifier.Text).Reverse();
        return CreateRegion(node, string.Join(".", containing.Append(name)), node.Kind().ToString(), Owned(node).ToArray(), path);
    }

    private static Region CreateRegion(SyntaxNode node, string name, string kind, SyntaxNode[] owned, string path)
    {
        var statements = owned.Count(n => n is StatementSyntax and not (BlockSyntax or EmptyStatementSyntax or LocalFunctionStatementSyntax));
        if (node.ChildNodes().Any(n => n is ArrowExpressionClauseSyntax) || node is LambdaExpressionSyntax { Body: ExpressionSyntax }) statements++;
        var branches = owned.Count(n => n is IfStatementSyntax or ForStatementSyntax or ForEachStatementSyntax or ForEachVariableStatementSyntax or WhileStatementSyntax or DoStatementSyntax or CatchClauseSyntax or ConditionalExpressionSyntax or CaseSwitchLabelSyntax or CasePatternSwitchLabelSyntax
            || n is SwitchExpressionArmSyntax { Pattern: not DiscardPatternSyntax }
            || n.IsKind(SyntaxKind.LogicalAndExpression) || n.IsKind(SyntaxKind.LogicalOrExpression) || n.IsKind(SyntaxKind.CoalesceExpression) || n.IsKind(SyntaxKind.CoalesceAssignmentExpression) || n.IsKind(SyntaxKind.AndPattern) || n.IsKind(SyntaxKind.OrPattern));
        bool Control(SyntaxNode n) => n is IfStatementSyntax or ForStatementSyntax or ForEachStatementSyntax or ForEachVariableStatementSyntax or WhileStatementSyntax or DoStatementSyntax or SwitchStatementSyntax or CatchClauseSyntax or ConditionalExpressionSyntax;
        var nesting = owned.Where(Control).Select(n => 1 + n.Ancestors().TakeWhile(a => a != node).Count(Control)).DefaultIfEmpty(0).Max();
        int? parameters = node switch
        {
            BaseMethodDeclarationSyntax m => m.ParameterList.Parameters.Count,
            LocalFunctionStatementSyntax l => l.ParameterList.Parameters.Count,
            ParenthesizedLambdaExpressionSyntax l => l.ParameterList.Parameters.Count,
            SimpleLambdaExpressionSyntax => 1,
            AnonymousMethodExpressionSyntax a => a.ParameterList?.Parameters.Count ?? 0,
            _ => null
        };
        return new($"{path}:{node.SpanStart}", name, kind, Line(node), node.GetLocation().GetLineSpan().EndLinePosition.Line + 1, statements, 1 + branches, nesting, parameters);
    }
    private static int Line(SyntaxNode node) => node.GetLocation().GetLineSpan().StartLinePosition.Line + 1;
}
